# -*- coding: utf-8 -*-
"""Finds the vendored pycryptodomex for this CPU (INTG-KODI-01: fallback when the system has no usable libcrypto).

Layout (see vendor/MANIFEST.json, regenerated by tools/vendor_wheels.py)::

    vendor/<platform_key>/Cryptodome/...      unmodified upstream pycryptodomex 3.24.2 modules, pruned to what we use
    platform_key in: linux-x86_64, linux-aarch64, linux-armv7l, windows-amd64, macos-universal

The compiled parts are loaded in-process by Python; nothing is started as a separate program.

pycryptodomex API the addon relies on (all present in 3.24.2; checked by tests/test_vendor_loader.py):
  * AES-GCM : ``from Cryptodome.Cipher import AES``; ``AES.new(key, AES.MODE_GCM, nonce=iv)``; ``.update(aad)``;
              ``.encrypt_and_digest(pt)`` / ``.decrypt_and_verify(ct, tag)``.
  * HMAC/SHA: ``Cryptodome.Hash.HMAC`` / ``SHA256``; HKDF: ``Cryptodome.Protocol.KDF.HKDF`` (crypto.py also has a pure-Python HKDF).
  * X25519  : ``from Cryptodome.PublicKey import ECC``; ``ECC.generate(curve="Curve25519")``;
              ``from Cryptodome.Protocol.DH import import_x25519_private_key, import_x25519_public_key, key_agreement``;
              ``key_agreement(static_priv=priv, static_pub=pub, kdf=lambda shared: shared)`` returns the 32-byte shared secret;
              ``key.public_key().export_key(format="raw")`` is the 32-byte public key.
  * Random  : ``Cryptodome.Random.get_random_bytes``.

Forcing the fallback (for testing): set env ``SB_FORCE_CRYPTODOME=1`` or create an empty file ``force_cryptodome`` in the
add-on data directory. ``crypto._load_backend`` then skips the system libcrypto.
"""
import importlib
import os
import platform
import sys

VENDOR_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "vendor")
_PROBE_MODULES = ("Cryptodome.Cipher.AES",)
FORCE_ENV = "SB_FORCE_CRYPTODOME"
FORCE_FILE = "force_cryptodome"

_result = None


def log(message, level="info"):
    try:
        import compat
        compat.log(message, level)
    except Exception:  # noqa: BLE001 - logging must never break crypto loading
        sys.stderr.write("[SpaceBadger] %s\n" % message)


def platform_key(system=None, machine=None, maxsize=None):
    """Vendor sub-directory name for this machine, e.g. ``linux-armv7l``. Pure; arguments are injectable for tests.

    Kodi on OSMC/LibreELEC Pi images is often a 32-bit userland on a 64-bit kernel: ``platform.machine()`` says
    ``aarch64`` there, but ``sys.maxsize`` is 2**31-1, so the 32-bit ARM build is the right one.
    Returns a key even for unsupported combinations (e.g. ``linux-i686``); callers check the directory exists.
    """
    system = (platform.system() if system is None else system).lower()
    machine = (platform.machine() if machine is None else machine).lower()
    maxsize = sys.maxsize if maxsize is None else maxsize
    is64 = maxsize > 2 ** 32
    if machine in ("x86_64", "amd64", "x64"):
        arch = "x86_64" if is64 else "i686"
    elif machine in ("i386", "i486", "i586", "i686", "x86"):
        arch = "i686"
    elif machine in ("aarch64", "arm64", "armv8", "armv8l", "armv8b", "arm64e"):
        arch = "aarch64" if is64 else "armv7l"
    elif machine.startswith("arm"):  # armv6l, armv7l, armv7, armhf, armel, arm
        arch = "armv7l"  # the armv6l/armv7l piwheels wheels are the same file
    else:
        arch = machine or "unknown"
    if system == "windows":
        return "windows-" + ("amd64" if arch == "x86_64" else "arm64" if arch == "aarch64" else arch)
    if system == "darwin":
        return "macos-universal"
    return "%s-%s" % (system or "unknown", arch)


def force_requested(data_dir=None):
    """True when the user/tester wants the vendored Cryptodome even though a system libcrypto works."""
    if os.environ.get(FORCE_ENV, "").strip().lower() in ("1", "true", "yes", "on"):
        return True
    try:
        if data_dir is None:
            import compat
            data_dir = compat.data_dir()
        return os.path.exists(os.path.join(data_dir, FORCE_FILE))
    except Exception:  # noqa: BLE001
        return False


def _purge_cryptodome():
    for name in [n for n in sys.modules if n == "Cryptodome" or n.startswith("Cryptodome.")]:
        del sys.modules[name]


def _import_probe():
    for name in _PROBE_MODULES:
        importlib.import_module(name)


def prepare(vendor_dir=None, key=None, force=False):
    """Make ``import Cryptodome`` work if at all possible. Never raises; returns (and caches) a status dict.

    Order: a Cryptodome that already imports (system site-packages, another add-on's path) wins; only otherwise
    ``vendor/<platform_key>`` is put on sys.path. ``force=True`` retries even if a previous call failed.
    status = {"ok": bool, "source": "system"|"vendored"|"none", "platform": key, "dir": path|None, "error": str|None}
    """
    global _result
    if _result is not None and not force:
        return _result
    key = key or platform_key()
    root = vendor_dir or VENDOR_DIR
    status = {"ok": False, "source": "none", "platform": key, "dir": None, "error": None}
    try:
        try:
            _import_probe()
            status.update(ok=True, source="system", dir=os.path.dirname(sys.modules["Cryptodome"].__file__))
            log("vendor_loader: system Cryptodome works (%s), vendored copy not needed" % status["dir"])
        except Exception as exc:  # noqa: BLE001 - ImportError, or a broken wrong-arch .so
            log("vendor_loader: no usable system Cryptodome (%s: %s); platform key %s" % (type(exc).__name__, exc, key))
            candidate = os.path.join(root, key)
            if not os.path.isdir(os.path.join(candidate, "Cryptodome")):
                status["error"] = "no vendored Cryptodome for platform %s in %s" % (key, root)
                log("vendor_loader: " + status["error"], "warning")
            else:
                _purge_cryptodome()
                if candidate not in sys.path:
                    sys.path.insert(0, candidate)
                importlib.invalidate_caches()
                log("vendor_loader: trying vendored %s" % candidate)
                try:
                    _import_probe()
                    status.update(ok=True, source="vendored", dir=candidate)
                    log("vendor_loader: vendored Cryptodome imported OK from %s" % candidate)
                except Exception as exc2:  # noqa: BLE001
                    status["error"] = "vendored import failed: %s: %s" % (type(exc2).__name__, exc2)
                    log("vendor_loader: " + status["error"], "error")
                    try:
                        sys.path.remove(candidate)
                    except ValueError:
                        pass
                    _purge_cryptodome()
    except Exception as exc:  # noqa: BLE001 - this function promises never to raise
        status["error"] = "unexpected: %s: %s" % (type(exc).__name__, exc)
        log("vendor_loader: " + status["error"], "error")
    _result = status
    return status


def last_status():
    """The status dict of the last prepare() call (None if it never ran)."""
    return _result
