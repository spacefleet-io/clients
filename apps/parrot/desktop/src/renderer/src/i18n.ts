export const PARROT_STRINGS: Record<ParrotLanguage, Strings> = { en, fr, nl, de, es };

export type Translate = (key: ParrotStringKey, vars?: Record<string, string | number>) => string;

export const translator =
  (language: ParrotLanguage): Translate =>
  (key, vars) =>
    (PARROT_STRINGS[language][key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`));

/** "1 album", "0 album" in French, "12 Alben": the language's own plural rule picks the form. */
export const countText = (language: ParrotLanguage, t: Translate, kind: "album" | "song" | "artist", n: number): string =>
  t(shellCountKey(language, kind, n), { n });

/**
 * What a failed sign-in shows: the sentence every app shares (`@space/shared/signInError`, ACCT-AUTH-11), except the
 * second-step prompt, which asks for the code Parrot's form now shows. `retryAfterMinutes` fills "too many attempts".
 */
export const signInFailureText = (language: ParrotLanguage, failure: SignInFailure, retryAfterMinutes?: number): string =>
  failure === "twoFactorRequired"
    ? translator(language)("signIn.codeNeeded")
    : signInErrorText(language, signInErrorMessage(failure), retryAfterMinutes);
