export const findMediaLanguage = (code: string) =>
  MEDIA_LANGUAGE_OPTIONS.find((lang) => lang.code === code) ?? null;

/** The flag for a media language: its country's ("fr" → 🇫🇷), 🌐 for "No language", "" when no country stands for it. */
export const getMediaLanguageFlag = (code: string) => {
  if (code === "xx") return "🌐";
  const country = MEDIA_LANGUAGE_COUNTRY[code];
  if (!country) return "";
  return String.fromCodePoint(...[...country].map((letter) => 0x1f1e6 + letter.charCodeAt(0) - 65));
};

export const formatMediaLanguageLabel = (code: string) => {
  const match = findMediaLanguage(code);
  if (!match) return code.toUpperCase();
  return match.nativeName || match.englishName || match.code.toUpperCase();
};

export const formatMediaLanguageOptionLabel = (code: string) => {
  const flag = getMediaLanguageFlag(code);
  const label = formatMediaLanguageLabel(code);
  return flag ? `${flag} ${label}` : label;
};
