/**
 * REL-LOG-06: the phone apps (Badger, Parrot) bake their reporting address in at build time from the environment; the
 * generated module is never committed and an unset variable means "cannot report".
 */
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { describeErrorReportEnv, renderErrorReportConfig, writeErrorReportConfigFile } from "../src/buildConfig";

const P = "[build-config]";
const DSN = "https://k3y@reports.example.test/7";

describe("@req REL-LOG-06[badger-mobile,parrot] build-time reporting address", () => {
  it("renders one constant per entry, empty when unset, trimmed and escaped", () => {
    const text = renderErrorReportConfig({ PARROT_MOBILE_DSN: ` ${DSN}\n`, OTHER_DSN: undefined, ODD: 'a"b' }, "test");
    console.info(`${P} phase=render\n${text}`);
    expect(text).toContain("Generated by test");
    expect(text).toContain(`export const PARROT_MOBILE_DSN = "${DSN}";`);
    expect(text).toContain('export const OTHER_DSN = "";');
    expect(text).toContain('export const ODD = "a\\"b";');
  });

  it("writes the module, creating its folder", () => {
    const dir = mkdtempSync(join(tmpdir(), "sf-build-config-"));
    try {
      const path = join(dir, "generated", "errorReportConfig.ts");
      writeErrorReportConfigFile(path, { PARROT_MOBILE_DSN: DSN }, "test");
      const written = readFileSync(path, "utf8");
      console.info(`${P} phase=write path=${path}`);
      expect(written).toBe(renderErrorReportConfig({ PARROT_MOBILE_DSN: DSN }, "test"));
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("describes which variables are set without printing a value", () => {
    const lines = describeErrorReportEnv({ A: DSN, B: " " }, ["A", "B", "C"]);
    console.info(`${P} phase=describe\n${lines.join("\n")}`);
    expect(lines.join("\n")).not.toContain("k3y");
    expect(lines).toEqual([
      "[error-report-config] A set",
      "[error-report-config] B empty (cannot report)",
      "[error-report-config] C empty (cannot report)",
    ]);
  });
});
