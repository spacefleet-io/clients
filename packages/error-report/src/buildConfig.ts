import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

/**
 * Build-time DSNs for the React Native apps (REL-LOG-06), shared by Badger and Parrot: each app's
 * `scripts/write-error-report-config.ts` names its constants and the environment variables they come from, and this
 * writes the gitignored module the app reads (`src/generated/errorReportConfig.ts`). A DSN is never committed; an
 * unset variable becomes an empty string, which means that build cannot report.
 */
export type ErrorReportConfigEntries = Record<string, string | undefined>;

/** Source text of the generated module; values are JSON-escaped so any env content stays a plain string literal. */
export const renderErrorReportConfig = (entries: ErrorReportConfigEntries, generator: string): string =>
  [
    `// Generated by ${generator} from the build environment. Gitignored: do not commit.`,
    ...Object.entries(entries).map(([name, value]) => `export const ${name} = ${JSON.stringify((value ?? "").trim())};`),
    "",
  ].join("\n");

export const writeErrorReportConfigFile = (path: string, entries: ErrorReportConfigEntries, generator: string): void => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, renderErrorReportConfig(entries, generator));
};

/** One log line per variable: whether it was set, never its value. */
export const describeErrorReportEnv = (env: Record<string, string | undefined>, names: readonly string[]): string[] =>
  names.map((name) => `[error-report-config] ${name} ${(env[name] ?? "").trim() ? "set" : "empty (cannot report)"}`);
