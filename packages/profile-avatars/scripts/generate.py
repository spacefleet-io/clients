#!/usr/bin/env python3
"""Draws the shipped sizes of the 22 profile avatars (ACCT-PROF-05) from their 512 px sources.

Run from anywhere: `python3 packages/profile-avatars/scripts/generate.py` (needs Pillow). It rewrites `assets/` and the
two generated entries (`src/web.ts`, `src/native.ts`); commit them together with any change here or in `source/`.
The list of avatars is `PROFILE_AVATAR_IDS` in `packages/shared/src/profileAvatars.ts`; a source missing or extra fails.

Sizes (WebP, quality 82):
- 64 px: web, desktop and Parrot desktop at up to 32 px CSS (top-bar button, menu rows) on a 2x screen;
- 256 px: everything larger (Who's watching tiles, the chooser grid and preview, phone and TV), on any screen.
"""

from __future__ import annotations

import re
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
PACKAGE = HERE.parent
ROOT = PACKAGE.parents[1]
SIZES = (64, 256)
QUALITY = 82

HEADER = "// Generated by packages/profile-avatars/scripts/generate.py from source/: do not edit.\n"


def avatar_ids() -> list[str]:
    text = (ROOT / "packages/shared/src/profileAvatars.ts").read_text()
    block = re.search(r"PROFILE_AVATAR_IDS = \[(.*?)\] as const", text, re.S)
    if not block:
        raise SystemExit("PROFILE_AVATAR_IDS not found in packages/shared/src/profileAvatars.ts")
    return re.findall(r'"([a-z]+)"', block.group(1))


def draw(ids: list[str]) -> None:
    sources = {path.stem for path in (PACKAGE / "source").glob("*.webp")}
    if sources != set(ids):
        raise SystemExit(f"source/ does not match PROFILE_AVATAR_IDS: missing {sorted(set(ids) - sources)}, extra {sorted(sources - set(ids))}")
    for size in SIZES:
        folder = PACKAGE / "assets" / str(size)
        folder.mkdir(parents=True, exist_ok=True)
        for stale in folder.glob("*.webp"):
            stale.unlink()
        total = 0
        for avatar in ids:
            art = Image.open(PACKAGE / "source" / f"{avatar}.webp").convert("RGB")
            out = folder / f"{avatar}.webp"
            art.resize((size, size), Image.LANCZOS).save(out, "WEBP", quality=QUALITY, method=6)
            total += out.stat().st_size
        print(f"assets/{size}: {len(ids)} files, {total // 1024} KB")


def camel(avatar: str, size: int) -> str:
    return f"{avatar}{size}"


def write_web(ids: list[str]) -> None:
    lines = [HEADER, 'import type { ProfileAvatarId } from "@space/shared/profileAvatars";\n']
    for avatar in ids:
        for size in SIZES:
            lines.append(f'import {camel(avatar, size)} from "../assets/{size}/{avatar}.webp";\n')
    lines.append("\n/** URL of each avatar per size, resolved by the bundler (Vite). */\n")
    lines.append("export const PROFILE_AVATAR_URLS: Record<ProfileAvatarId, { small: string; large: string }> = {\n")
    for avatar in ids:
        lines.append(f"  {avatar}: {{ small: {camel(avatar, 64)}, large: {camel(avatar, 256)} }},\n")
    lines.append("};\n")
    (PACKAGE / "src/web.ts").write_text("".join(lines))


def write_native(ids: list[str]) -> None:
    lines = [HEADER, 'import type { ProfileAvatarId } from "@space/shared/profileAvatars";\n\n']
    lines.append("/** Image source of each avatar (256 px), bundled by Metro. */\n")
    lines.append("export const PROFILE_AVATAR_SOURCES: Record<ProfileAvatarId, number> = {\n")
    for avatar in ids:
        lines.append(f'  {avatar}: require("../assets/256/{avatar}.webp") as number,\n')
    lines.append("};\n")
    (PACKAGE / "src/native.ts").write_text("".join(lines))


def main() -> None:
    ids = avatar_ids()
    draw(ids)
    write_web(ids)
    write_native(ids)
    print("wrote src/web.ts, src/native.ts")


if __name__ == "__main__":
    main()
